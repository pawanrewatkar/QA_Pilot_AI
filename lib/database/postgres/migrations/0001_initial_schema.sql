-- QA Pilot AI: PostgreSQL schema, migration 0001 (initial).
--
-- Equivalent of the SQLite schema after SQLite migrations 1-7 (lib/database/schema.ts), translated mechanically:
-- - Timestamps stay ISO-8601 UTC text; defaults produce the same text as SQLite's strftime('%Y-%m-%dT%H:%M:%fZ','now').
-- - JSON stays in TEXT columns; ids stay TEXT; booleans stay 0/1 INTEGER (what the repositories expect today).
-- - REAL -> DOUBLE PRECISION. INTEGER -> integer (4 bytes; the importer checks every value fits).
-- - The case-insensitive (COLLATE NOCASE) index on projects.name -> an index on lower(name).
-- - 15 tables get rowid (an identity column) to keep SQLite's insertion-order tie-break; see the docs.
-- - SQLite's own migration table (schema_migrations) is not copied: qa_pilot_migrations tracks these files.
-- - Row level security is enabled on every table with no policies, so Supabase's anon/authenticated roles
--   (the public Data API) cannot read or write them. The app connects server-side as the table owner,
--   which is not subject to RLS.
--
-- Do not edit this file once applied anywhere: the migrator verifies its checksum. Add a new migration instead.

